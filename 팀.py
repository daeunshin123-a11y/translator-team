def 팀원정보():
    """화면에 보여줄 팀원 소개 (지시문은 빼고)"""
    return [
        {키: 사람[키] for 키 in ("아이디", "이름", "얼굴", "색", "한줄소개")}
        for 사람 in 팀원들
    ]


def _물어보기(지시문, 질문):
    """주자를 순서대로 시도합니다. (답, 누가답했나)"""
    마지막오류 = None
    for 주자 in 공급자들:
        열쇠 = (os.environ.get(주자["열쇠이름"]) or "").strip()
        if not 열쇠 or any("가" <= 글 <= "힣" for 글 in 열쇠):
            continue
        이름표 = f'{주자["이름"]}/{주자["모델"]}'
        try:
            손님 = OpenAI(api_key=열쇠, base_url=주자["주소"], timeout=60)
            답 = 손님.chat.completions.create(
                model=주자["모델"],
                messages=[
                    {"role": "system", "content": 지시문},
                    {"role": "user", "content": 질문},
                ],
                max_tokens=400,
            )
            글 = (답.choices[0].message.content or "").strip()
            if 글:
                return 글, 이름표
            raise RuntimeError("빈 답변")
        except Exception as 오류:
            마지막오류 = 오류
            로그.warning("%s 실패 → 다음 주자: %s", 이름표, type(오류).__name__)
    raise RuntimeError(f"모든 모델 실패: {마지막오류}")


def 회의하기(표현):
    """팀원들이 차례로 일하는 과정을 하나씩 흘려보냅니다(제너레이터).

    보내는 소식의 종류
      시작   : 회의 시작
      상태   : 누가 지금 뭘 하는 중인지 (일하는중 / 기다리는중 / 쉬는중)
      말풍선 : 누가 무슨 말을 했는지
      넘김   : 누구에게서 누구에게로 바통이 넘어갔는지
      끝     : 최종 결과
      오류   : 실패
    """
    yield {"종류": "시작", "표현": 표현}

    이전사람 = None
    쌓인메모 = []

    for 사람 in 팀원들:
        yield {"종류": "상태", "누구": 사람["아이디"], "상태": "일하는중"}
        if 이전사람:
            yield {
                "종류": "넘김",
                "부터": 이전사람["아이디"],
                "까지": 사람["아이디"],
            }

        질문 = f"[번역할 표현]\n{표현}\n"
        if 쌓인메모:
            질문 += "\n[앞사람들의 메모]\n" + "\n\n".join(쌓인메모)

        try:
            답, 누가 = _물어보기(사람["지시문"], 질문)
        except Exception as 오류:
            yield {"종류": "상태", "누구": 사람["아이디"], "상태": "쉬는중"}
            yield {"종류": "오류", "내용": str(오류)[:200]}
            return

        쌓인메모.append(f"[{사람['이름']}]\n{답}")

        yield {
            "종류": "말풍선",
            "누구": 사람["아이디"],
            "내용": 답,
            "모델": 누가,
        }
        yield {"종류": "상태", "누구": 사람["아이디"], "상태": "쉬는중"}
        이전사람 = 사람

    yield {"종류": "끝", "결과": 쌓인메모[-1] if 쌓인메모 else ""}
