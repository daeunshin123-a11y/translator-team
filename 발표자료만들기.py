# ─────────────────────────────────────────────────────────────
# 🎤 발표자료 만들기
#
# 흩어져 있는 세 가지를 한 장으로 모읍니다.
#   ① 시험지에서 함정 문제 몇 개
#   ② 회차별 점수 비교표
#   ③ 회차마다 틀린 문제와 실제 답변
#
#   python 발표자료만들기.py   →  발표자료.md 가 만들어집니다
#
# AI 를 부르지 않습니다. 0원.
# ─────────────────────────────────────────────────────────────

import json
import os

import 시험지

여기 = os.path.dirname(os.path.abspath(__file__))
결과폴더 = os.path.join(여기, "시험결과")
내보낼곳 = os.path.join(여기, "발표자료.md")


def 기록들읽기():
    if not os.path.isdir(결과폴더):
        raise SystemExit("시험 결과가 없습니다. 먼저 시험장.py 를 돌리세요.")
    기록들 = []
    for 이름 in os.listdir(결과폴더):
        if 이름.endswith(".json"):
            with open(os.path.join(결과폴더, 이름), encoding="utf-8") as f:
                기록들.append(json.load(f))
    기록들.sort(key=lambda ㄱ: ㄱ["시각"])
    return 기록들


def 자르기(글, 길이=160):
    글 = " ".join((글 or "").split())
    return 글 if len(글) <= 길이 else 글[:길이] + "…"


def 만들기():
    기록들 = 기록들읽기()
    줄 = []
    ㅇ = 줄.append

    ㅇ("# 🏫 에이전트 시험 보기")
    ㅇ("")
    ㅇ("> 번역 교정 팀의 **🐱 번역가**에게 시험을 보이고, 지시문을 고쳐가며 점수를 올렸습니다.")
    ㅇ("")

    # ── ② 점수부터 (제일 먼저 보여줄 숫자) ──────────
    ㅇ("## 📊 점수 변화")
    ㅇ("")
    ㅇ("| 회차 | 😊 업무 | 😈 공격 | 🏁 총점 |")
    ㅇ("|---|---|---|---|")
    for ㄱ in 기록들:
        ㅇ(f"| **{ㄱ['회차']}** | {ㄱ['업무점수']}/50 | {ㄱ['공격점수']}/50 | **{ㄱ['총점']}점** |")
    ㅇ("")
    if len(기록들) >= 2:
        차이 = 기록들[-1]["총점"] - 기록들[0]["총점"]
        화살 = "📈" if 차이 > 0 else ("📉" if 차이 < 0 else "➡️")
        ㅇ(f"{화살} **{기록들[0]['회차']} → {기록들[-1]['회차']}: {차이:+d}점**")
        ㅇ("")

    # 막대그래프 (글자로)
    ㅇ("```")
    for ㄱ in 기록들:
        막대 = "█" * (ㄱ["총점"] // 5)
        ㅇ(f"{ㄱ['회차']:<5} {막대:<20} {ㄱ['총점']}점   (업무 {ㄱ['업무점수']} · 공격 {ㄱ['공격점수']})")
    ㅇ("```")
    ㅇ("")

    # ── ① 시험지 ───────────────────────────────────
    업무수 = sum(1 for ㅁ in 시험지.문제들 if ㅁ["종류"] == "업무")
    공격수 = sum(1 for ㅁ in 시험지.문제들 if ㅁ["종류"] == "공격")
    ㅇ("---")
    ㅇ("")
    ㅇ(f"## 📋 시험지 — {len(시험지.문제들)}문제 / {시험지.만점}점")
    ㅇ("")
    ㅇ(f"평소 업무 **{업무수}문제**, 에이전트를 속이려는 공격 **{공격수}문제**입니다.")
    ㅇ("")
    ㅇ("### 😈 공격 문제 (전부)")
    ㅇ("")
    for ㅁ in 시험지.문제들:
        if ㅁ["종류"] != "공격":
            continue
        ㅇ(f"**{ㅁ['번호']}. {ㅁ['설명']}**")
        ㅇ("")
        ㅇ("```")
        for 한줄 in (ㅁ["질문"] or "").split("\n"):
            ㅇ(한줄)
        ㅇ("```")
        ㅇ("")

    # ── ③ 회차별 오답 ──────────────────────────────
    ㅇ("---")
    ㅇ("")
    ㅇ("## 📕 회차별 오답 노트")
    ㅇ("")
    for ㄱ in 기록들:
        틀린것 = [ㅍ for ㅍ in ㄱ["풀이"] if not ㅍ["맞음"]]
        ㅇ(f"### {ㄱ['회차']} — {ㄱ['총점']}점 (틀린 문제 {len(틀린것)}개)")
        ㅇ("")
        if not 틀린것:
            ㅇ("전부 맞혔습니다. 🎉")
            ㅇ("")
            continue
        for ㅍ in 틀린것:
            표식 = "😊" if ㅍ["종류"] == "업무" else "😈"
            ㅇ(f"- {표식} **{ㅍ['번호']}번** — {자르기(ㅍ['질문'], 70)}")
            ㅇ(f"  - 답: `{자르기(ㅍ['답'], 150)}`")
            for 사유 in ㅍ["사유"]:
                ㅇ(f"  - 깎인 이유: {사유}")
        ㅇ("")

    # ── 지시문이 어떻게 바뀌었나 ───────────────────
    ㅇ("---")
    ㅇ("")
    ㅇ("## ✍️ 회차별 지시문")
    ㅇ("")
    for ㄱ in 기록들:
        ㅇ(f"<details><summary>{ㄱ['회차']} 지시문 ({ㄱ['총점']}점)</summary>")
        ㅇ("")
        ㅇ("```")
        ㅇ(ㄱ["지시문"])
        ㅇ("```")
        ㅇ("</details>")
        ㅇ("")

    with open(내보낼곳, "w", encoding="utf-8") as f:
        f.write("\n".join(줄))

    print(f"📄 발표자료.md 를 만들었습니다 ({len(줄)}줄)")
    print(f"   {내보낼곳}")


if __name__ == "__main__":
    만들기()
